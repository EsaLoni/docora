def test_jwt_verification_rejects_none_algorithm():
    """Verify tokens using alg: none are strictly rejected."""
    payload = {"sub": "user-123", "exp": int(time.time()) + 3600}
    encoded = jwt.encode(payload, key="", algorithm="none")

    with pytest.raises(AuthenticationFailedError, match="Insecure token algorithm is forbidden"):
        verify_jwt_token(encoded)


def test_jwt_verification_rejects_invalid_audience():
    """Verify tokens with mismatched audience claims are rejected."""
    settings = Settings(
        SUPABASE_JWT_SECRET=SecretStr("test-secret-key-min32chars-for-testing!!"),
        SUPABASE_JWT_AUDIENCE="expected-audience",
    )
    token = jwt.encode(
        {"sub": "user-123", "aud": "wrong-audience", "exp": int(time.time()) + 3600},
        key=settings.SUPABASE_JWT_SECRET.get_secret_value(),
        algorithm="HS256",
    )

    with pytest.raises(AuthenticationFailedError, match="Token audience is invalid"):
        verify_jwt_token(token, settings=settings)


def test_sliding_window_rate_limiter():
    """Verify rate limiter permits allowed calls and blocks exceeding calls."""
    limiter = SlidingWindowRateLimiter()
    key = "test_client_ip"
    max_calls = 3
    window = 10.0

    # 3 calls allowed
    for _ in range(max_calls):
        allowed, _ = limiter.is_allowed(key, max_calls=max_calls, window_seconds=window)
        assert allowed is True

    # 4th call blocked
    allowed, retry_after = limiter.is_allowed(key, max_calls=max_calls, window_seconds=window)
    assert allowed is False
    assert retry_after > 0


def test_zip_bomb_detection():
    """Verify FileValidator detects and rejects high-expansion zip bombs."""
    validator = FileValidator()

    # Create an in-memory zip archive with extreme compression (repeating zeros)
    zip_buffer = io.BytesIO()
    with zipfile.ZipFile(zip_buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        # 1.5MB of repeating zeros compresses down to < 2KB (ratio > 700:1)
        large_content = b"0" * 1_500_000
        zf.writestr("word/document.xml", large_content)

    compressed_bytes = zip_buffer.getvalue()

    with pytest.raises(IngestionValidationError, match="Potential zip bomb detected"):
        validator.validate("test_contract.docx", compressed_bytes)


def test_malware_heuristic_scanner_pe_header():
    """Verify HeuristicMalwareScanner flags embedded Windows PE executable binaries."""
    scanner = HeuristicMalwareScanner()
    # Executable with DOS MZ header
    fake_exe = b"MZ\x90\x00\x03\x00\x00\x00" + b"\x00" * 100
    res = scanner.scan(fake_exe, "document.pdf")
    assert res.is_clean is False
    assert res.threat_name == "EMBEDDED_EXECUTABLE_BINARY"


