def test_security_headers_present(client: TestClient):
    """Verify standard OWASP recommended defense-in-depth headers on responses."""
    response = client.get("/health/live")
    assert response.headers.get("X-Content-Type-Options") == "nosniff"
    assert response.headers.get("X-Frame-Options") == "DENY"
    assert response.headers.get("X-XSS-Protection") == "1; mode=block"
    assert response.headers.get("Referrer-Policy") == "strict-origin-when-cross-origin"
    assert "Content-Security-Policy" in response.headers


def test_correlation_id_propagation(client: TestClient):
    """Verify incoming X-Request-ID is preserved or freshly generated."""
    # Case 1: Provided by caller
    custom_id = "test-corr-id-12345"
    resp = client.get("/health/live", headers={"X-Request-ID": custom_id})
    assert resp.headers.get("X-Request-ID") == custom_id

    # Case 2: Generated by server if omitted
    resp2 = client.get("/health/live")
    generated_id = resp2.headers.get("X-Request-ID")
    assert generated_id is not None
    assert len(generated_id) >= 16


